#!/usr/bin/env node
// Delivery rooms: static checks, traversability of every placement, and maps
// generated from many seeds (docs/design/delivery-maps.md). Uses the lab tile
// model (no monsters, no timing): it proves that every route a generated map
// can ask for exists without items and without a fall that hurts. It is not
// real-time and not SDK verification.
// Usage: node tools/check-rooms.mjs [--write] [--seeds N] [--root dir]
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT as REPO, loadCore } from "./lib/load-core.mjs";

const sha = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".json") ? [path.join(dir, e.name)] : []));
}

// Loads every room template under content/rooms/ (format pushbox.room/1).
export function loadRooms(root) {
  return walk(path.join(root, "content/rooms")).map((f) => {
    const buf = fs.readFileSync(f);
    return { file: path.relative(root, f).split(path.sep).join("/"), sha256: sha(buf), room: JSON.parse(buf.toString("utf8")) };
  }).filter((x) => x.room.format === "pushbox.room/1");
}

export function checkRooms(root, opts = {}) {
  const PB = loadCore(["tilemodel", "rooms", "mapgen"]);
  const seeds = opts.seeds || 300;
  const catalog = (n) => readJson(path.join(root, "content/catalog", n + ".json")).entries;
  const monsters = new Map(catalog("monsters").map((m) => [m.id, m]));
  const slices = catalog("slices");
  const rooms = loadRooms(root);
  const report = { format: "pushbox.rooms-check/1", note: "Generated by `node tools/check-rooms.mjs --write`. Tile-model traversability only (no monsters, no timing): not real-time or SDK verification.", templates: [], slices: [] };
  const placementOk = new Map(), placementPar = new Map();
  let failed = 0;
  for (const { file, sha256, room: t } of rooms) {
    const v = PB.rooms.validate(t, { monsters, world: t.world });
    const entry = { id: t.id, file, sha256, type: t.type, world: t.world, errors: v.errors, warnings: v.warnings, placements: [] };
    if (!v.errors.length) {
      for (const p of PB.rooms.placements(t)) {
        const res = PB.rooms.checkPlacement(t, p);
        for (const r of res.routes) r.par_secs = r.ok ? PB.rooms.parSecs(r.ticks) : null;
        entry.placements.push(res);
        placementOk.set(res.key, res.ok);
        placementPar.set(res.key, res.routes);
        if (!res.ok) failed++;
      }
    } else failed++;
    report.templates.push(entry);
  }
  const byId = new Map(rooms.map((x) => [x.room.id, x.room]));
  const golden = [];
  for (const sl of slices) {
    const list = (sl.rooms || []).map((id) => byId.get(id)).filter(Boolean).sort((a, b) => a.id.localeCompare(b.id));
    const out = { id: sl.id, seeds, ok: true, failures: [], path_lengths: {}, directions: {}, template_use: {}, par_secs: null };
    if (!list.length) { out.ok = false; out.failures.push("切片没有房间模板"); report.slices.push(out); failed++; continue; }
    const pars = [];
    for (let seed = 1; seed <= seeds; seed++) {
      let map;
      try { map = PB.mapgen.generate(seed, sl, list); } catch (e) { out.ok = false; out.failures.push(`种子 ${seed}：${e.message}`); continue; }
      out.path_lengths[map.path.length] = (out.path_lengths[map.path.length] || 0) + 1;
      out.directions[map.dir] = (out.directions[map.dir] || 0) + 1;
      let par = 0;
      for (const r of map.rooms) {
        out.template_use[r.template] = (out.template_use[r.template] || 0) + 1;
        const key = PB.rooms.placementKey(r.template, r.mirror, r.open);
        if (placementOk.get(key) !== true) { out.ok = false; out.failures.push(`种子 ${seed} 房间 ${r.index}（${key}）没有通过可通性检查`); continue; }
        par += routePar(PB, map, r, placementPar.get(key));
      }
      map.par_secs = par;
      pars.push(par);
      if (seed <= 30) golden.push(map);
    }
    if (pars.length) out.par_secs = { min: Math.min(...pars), max: Math.max(...pars), avg: Math.round((pars.reduce((a, b) => a + b, 0) / pars.length) * 10) / 10 };
    if (!out.ok) failed++;
    out.failures = out.failures.slice(0, 20);
    report.slices.push(out);
  }
  return { report, golden, failed };
}

// Reference seconds a map room contributes: the route from where the path comes in to where it goes on.
function routePar(PB, map, r, routes) {
  const name = (e) => e + "." + r.open[e];
  const prev = r.index > 0 ? map.rooms[r.index - 1] : null, next = r.index < map.rooms.length - 1 ? map.rooms[r.index + 1] : null;
  const from = prev ? name(PB.rooms.edgeToward([r.x, r.y], [prev.x, prev.y])) : "gate";
  const to = next ? name(PB.rooms.edgeToward([r.x, r.y], [next.x, next.y])) : "recipient";
  const hit = (routes || []).find((x) => x.from === from && x.to === to);
  return hit && hit.par_secs ? hit.par_secs : 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const argv = process.argv.slice(2);
  const opt = (n, d) => { const i = argv.indexOf("--" + n); return i >= 0 ? argv[i + 1] : d; };
  const root = path.resolve(opt("root", REPO));
  const { report, golden, failed } = checkRooms(root, { seeds: Number(opt("seeds", 300)) });
  for (const t of report.templates) {
    const ok = !t.errors.length && t.placements.every((p) => p.ok);
    const routes = t.placements.flatMap((p) => p.routes);
    console.log(`${ok ? "ok   " : "FAIL "} ${t.id.padEnd(22)} ${t.type.padEnd(8)} placements=${t.placements.length} routes=${routes.length} max_steps=${Math.max(0, ...routes.map((r) => r.steps || 0))} dig=${routes.filter((r) => r.needs_dig).length}`);
    for (const e of t.errors) console.log("      error: " + e);
    for (const w of t.warnings) console.log("      warn:  " + w);
    for (const p of t.placements) for (const r of p.routes) if (!r.ok) console.log(`      route ${p.key} ${r.from} -> ${r.to}: unreachable (${r.explored} states${r.capped ? ", search limit" : ""})`);
  }
  for (const s of report.slices) {
    console.log(`${s.ok ? "ok   " : "FAIL "} slice ${s.id}: ${s.seeds} seeds, path lengths ${JSON.stringify(s.path_lengths)}, directions ${JSON.stringify(s.directions)}, par ${JSON.stringify(s.par_secs)}`);
    console.log("      templates used: " + Object.entries(s.template_use).map(([k, v]) => k + " " + v).join(", "));
    for (const f of s.failures) console.log("      " + f);
  }
  if (argv.includes("--write")) {
    fs.writeFileSync(path.join(root, "content/rooms-check.generated.json"), JSON.stringify(report, null, 1) + "\n");
    fs.mkdirSync(path.join(root, "content/export"), { recursive: true });
    fs.writeFileSync(path.join(root, "content/export/delivery-golden.json"), JSON.stringify({ format: "pushbox.delivery-golden/1", note: "Generated by `node tools/check-rooms.mjs --write`. The game's map generator must reproduce these maps exactly (template, mirror, open exits, path, direction) for the same seed and slice.", maps: golden }, null, 1) + "\n");
    console.log("wrote content/rooms-check.generated.json and content/export/delivery-golden.json");
  }
  process.exit(failed ? 1 : 0);
}
