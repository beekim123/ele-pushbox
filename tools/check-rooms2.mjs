#!/usr/bin/env node
// Delivery rooms of format pushbox.room/2 (docs/design/delivery-puzzle-rules.md):
// static checks, every route of every room (and of its mirror) solved by
// breadth-first search in the tile model plus float blocks (rooms2.js), the
// author's solution replayed, "this mechanic is required" (search again with it
// frozen), hint steps finished in order along the author's solution, monsters
// outside the puzzle area, and runs generated from many seeds with the three
// reels and the layout of mapgen2.js. Turn-based only: no monsters, no timing,
// no SDK. Usage: node tools/check-rooms2.mjs [--write] [--seeds N] [--root dir] [--only id]
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { ROOT as REPO, loadCore } from "./lib/load-core.mjs";

const sha = (buf) => crypto.createHash("sha256").update(buf).digest("hex");
const readJson = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
function walk(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : e.name.endsWith(".json") ? [path.join(dir, e.name)] : []));
}
export function loadRooms2(root) {
  return walk(path.join(root, "content/rooms")).map((f) => {
    const buf = fs.readFileSync(f);
    return { file: path.relative(root, f).split(path.sep).join("/"), sha256: sha(buf), room: JSON.parse(buf.toString("utf8")) };
  }).filter((x) => x.room.format === "pushbox.room/2");
}
const SPECIAL = new Set(["gate", "recipient"]);
// What a pool's runs depend on besides the room files (those are checked by their own sha256):
// the pool entry and the map slices it draws from. tools/content.mjs compares it.
export function poolInput(pool, maps) {
  return sha(JSON.stringify({ pool, maps: pool.pool.maps.map((m) => maps.get(m.slice) || null) }));
}

// One route of one placement: shortest path, author's solution, required mechanics, hints.
function checkRoute(PB, room, mirror, route, limit) {
  const R = PB.rooms2, W = (room.size || [1, 1])[0];
  const [a0, b0] = route.split(">");
  const f = (id) => (SPECIAL.has(id) || !mirror ? id : R.mirrorExit(id, W));
  const a = f(a0), b = f(b0);
  const v = R.variant(room, mirror, [a, b].filter((x) => !SPECIAL.has(x)));
  const out = { route, mirror, from: a, to: b, ok: true, errors: [], warnings: [] };
  const t0 = Date.now();
  const res = R.solve(v, a, b, { limit });
  out.explored = res.explored; out.ms = Date.now() - t0;
  if (!res.solved) { out.ok = false; out.errors.push(res.exhausted ? "走不通" : `搜索 ${limit} 个状态内没找到路`); return out; }
  out.shortest = res.solution.length;
  const sol = (room.solutions || {})[route];
  let actions = res.solution;
  if (sol) {
    actions = R.expand(sol); if (mirror) actions = R.mirrorActions(actions);
    const rep = R.replay(v, a, b, actions);
    if (!rep.reached) { out.ok = false; out.errors.push(rep.failedAt !== undefined ? `作者解第 ${rep.failedAt + 1} 步 ${rep.action} 做不了（${rep.reason}）` : "作者解没有走到出口"); }
    out.author = actions.length;
  }
  out.actions = actions;
  for (const m of room.requires || []) {
    const fr = R.solve(v, a, b, { limit, frozen: [m] });
    if (fr.solved) { out.ok = false; out.errors.push(`不用「${m}」也能过（${fr.solution.length} 步）`); }
    else if (!fr.exhausted) out.warnings.push(`关掉「${m}」后搜索到上限，无法确认它是必需的`);
  }
  if ((room.hints || []).length && route === (room.hint_route || (room.routes || [])[0])) {
    const rep = R.replay(v, a, b, actions);
    const tr = R.hintTrace(rep);
    out.hints = { first: tr.first, ok: tr.ok };
    if (!tr.ok) { out.ok = false; out.errors.push(...tr.problems); }
  }
  return out;
}

export function checkRooms2(root, opts = {}) {
  const PB = loadCore(["tilemodel", "rooms2", "mapgen", "mapgen2"]);
  const R = PB.rooms2, limit = opts.limit || 250000, seeds = opts.seeds || 300;
  const catalog = (n) => readJson(path.join(root, "content/catalog", n + ".json")).entries;
  const rooms = loadRooms2(root).filter((x) => !opts.only || x.room.id === opts.only);
  const report = { format: "pushbox.rooms2-check/1", note: "Generated by `node tools/check-rooms2.mjs --write`. Tile model + float blocks, breadth-first search; no monsters, no timing; not SDK verification.", templates: [], pools: [] };
  const ok = new Map();
  let failed = 0;
  for (const { file, sha256, room } of rooms) {
    const t = { id: room.id, file, sha256, world: room.world, role: room.role, size: room.size || [1, 1], errors: R.validate(room), routes: [], warnings: [] };
    if (!t.errors.length) {
      for (const mirror of room.mirror === false ? [false] : [false, true]) {
        const v = R.variant(room, mirror, null);
        for (const p of R.monsterProblems(v)) t.errors.push((mirror ? "（翻转）" : "") + p);
        for (const route of room.routes || []) {
          const r = checkRoute(PB, room, mirror, route, limit);
          t.routes.push(r);
          ok.set(room.id + "|" + mirror + "|" + route, r.ok);
          if (!r.ok) for (const e of r.errors) t.errors.push(`${mirror ? "翻转 " : ""}${route}：${e}`);
          for (const w of r.warnings) t.warnings.push(`${mirror ? "翻转 " : ""}${route}：${w}`);
          delete r.actions;
        }
      }
    }
    if (t.errors.length) failed++;
    report.templates.push(t);
  }
  // Runs from the pools.
  if (!opts.only) {
    const slices = catalog("slices"), maps = new Map(slices.filter((s) => s.format === 2).map((s) => [s.id, s]));
    const cat = { recipients: new Map(catalog("recipients").map((e) => [e.id, e])), cargo: new Map(catalog("cargo").map((e) => [e.id, e])) };
    const byId = new Map(rooms.map((x) => [x.room.id, x.room]));
    const templatesOf = (sid) => (maps.get(sid).rooms2 || []).map((id) => byId.get(id)).filter(Boolean);
    for (const pool of slices.filter((s) => s.pool)) {
      const out = { id: pool.id, input_sha256: poolInput(pool, maps), seeds, ok: true, failures: [], maps: {}, recipients: {}, cargo: {}, template_use: {}, rooms_per_run: {}, screens_per_run: {} };
      for (let seed = 1; seed <= seeds; seed++) {
        let m;
        try { m = PB.mapgen2.generate(seed, pool, maps, cat, templatesOf); } catch (e) { out.ok = false; if (out.failures.length < 10) out.failures.push(`种子 ${seed}：${e.message}`); continue; }
        out.maps[m.slice] = (out.maps[m.slice] || 0) + 1;
        out.recipients[m.recipient] = (out.recipients[m.recipient] || 0) + 1;
        out.cargo[m.cargo] = (out.cargo[m.cargo] || 0) + 1;
        out.rooms_per_run[m.rooms.length] = (out.rooms_per_run[m.rooms.length] || 0) + 1;
        const screens = m.rooms.reduce((s, r) => s + r.cols * r.rows, 0);
        out.screens_per_run[screens] = (out.screens_per_run[screens] || 0) + 1;
        const probs = PB.mapgen2.joints(m);
        for (const r of m.rooms) {
          out.template_use[r.template] = (out.template_use[r.template] || 0) + 1;
          if (ok.get(r.template + "|" + r.mirror + "|" + r.route) !== true) probs.push(`${r.template}${r.mirror ? "（翻转）" : ""} ${r.route} 没有通过检查`);
        }
        if (probs.length) { out.ok = false; if (out.failures.length < 10) out.failures.push(`种子 ${seed}：${probs[0]}`); }
      }
      if (!out.ok) failed++;
      report.pools.push(out);
    }
  }
  return { report, failed };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2), arg = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
  const root = arg("--root") ? path.resolve(arg("--root")) : REPO;
  const { report, failed } = checkRooms2(root, { seeds: Number(arg("--seeds")) || 300, only: arg("--only") });
  for (const t of report.templates) {
    const n = t.routes.length, good = t.routes.filter((r) => r.ok).length;
    const sh = t.routes.filter((r) => !r.mirror).map((r) => `${r.route} ${r.shortest ?? "×"}步${r.author ? "/作者" + r.author : ""}`).join("，");
    console.log(`${t.errors.length ? "✗" : "✓"} ${t.id} [${t.role} ${t.size.join("x")}] ${good}/${n} 条路线 ${sh}`);
    for (const e of t.errors) console.log("    " + e);
    for (const w of t.warnings) console.log("    提醒：" + w);
  }
  for (const p of report.pools) {
    console.log(`${p.ok ? "✓" : "✗"} 开局池 ${p.id}：${p.seeds} 个种子 地图 ${JSON.stringify(p.maps)} 房间数 ${JSON.stringify(p.rooms_per_run)}`);
    for (const f of p.failures) console.log("    " + f);
  }
  if (args.includes("--write") && !arg("--only")) {
    fs.writeFileSync(path.join(root, "content/rooms2-check.generated.json"), JSON.stringify(report, null, 1) + "\n");
    console.log("已写 content/rooms2-check.generated.json");
  }
  process.exit(failed ? 1 : 0);
}
