#!/usr/bin/env python3
"""Bake Fusion Pixel 12px glyphs used by the workbench into workbench/js/core/font-data.js.

Development tool only (needs Pillow); the browser and tools/art.mjs read the
generated file. Re-run after adding new UI strings or level titles.
"""
import hashlib, json, re
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "third_party/fonts/fusion-pixel-12px/fusion-pixel-12px-proportional-zh_hans.otf.woff2"
OUT = ROOT / "workbench/js/core/font-data.js"

chars = set(chr(i) for i in range(32, 127))
for path in list((ROOT / "workbench/js/core").glob("*.js")) + list((ROOT / "content/levels").rglob("*.json")) + list((ROOT / "art/source").rglob("*.json")) + list((ROOT / "content/i18n").glob("*.json")):
    if path.name == "font-data.js":
        continue
    chars.update(c for c in path.read_text(encoding="utf-8") if ord(c) > 127 and not c.isspace())
font = ImageFont.truetype(str(FONT), 12)
glyphs = {}
for ch in sorted(chars):
    adv = max(1, round(font.getlength(ch)))
    img = Image.new("1", (adv, 14))
    ImageDraw.Draw(img).text((0, 11), ch, font=font, fill=1, anchor="ls")
    rows = [sum(1 << x for x in range(adv) if img.getpixel((x, y))) for y in range(14)]
    glyphs[ch] = [adv] + rows
digest = hashlib.sha256(FONT.read_bytes()).hexdigest()
OUT.write_text(
    "/* Generated by tools/build-font.py from Fusion Pixel 12px (OFL, third_party/fonts/).\n"
    " * Source font SHA-256: " + digest + ". Do not edit by hand. */\n"
    "(function (root) {\n  const PB = (root.PB = root.PB || {});\n"
    "  PB.FONT = {height: 14, baseline: 11, glyphs: " + json.dumps(glyphs, ensure_ascii=False, separators=(",", ":")) + "};\n"
    "})(typeof window !== \"undefined\" ? window : globalThis);\n",
    encoding="utf-8",
)
print(f"{len(glyphs)} glyphs -> {OUT.relative_to(ROOT)}")
